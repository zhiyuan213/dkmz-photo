package com.dkmz.photo.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.*;

class PhotoCheckTicketServiceTest {
    private JdbcTemplate jdbc;
    private PhotoCheckTicketService tickets;

    @BeforeEach
    void setup() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:photo_check_" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE photo_processing_guard(id INT PRIMARY KEY)");
        jdbc.update("INSERT INTO photo_processing_guard(id) VALUES (1)");
        jdbc.execute("CREATE TABLE photo_check_ticket(token_hash CHAR(64) PRIMARY KEY, user_hash CHAR(64), "
                + "expires_at TIMESTAMP(3), consumed_at TIMESTAMP(3))");
        jdbc.execute("CREATE TABLE photo_check_request(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "user_hash CHAR(64), created_at TIMESTAMP(3))");
        tickets = new PhotoCheckTicketService(jdbc, new DataSourceTransactionManager(ds));
    }

    @Test
    void ticketIsUserBoundSingleUseAndSharedAcrossInstances() {
        String token = tickets.issue("user-a");
        assertFalse(tickets.consume(token, "user-b"));
        // 实例重建后仍可验证，适用于请求落到另一台容器。
        PhotoCheckTicketService other = new PhotoCheckTicketService(jdbc,
                new DataSourceTransactionManager(jdbc.getDataSource()));
        assertTrue(other.consume(token, "user-a"));
        assertFalse(tickets.consume(token, "user-a"));
    }

    @Test
    void expiredTicketAndExcessPrechecksAreRejected() {
        String token = tickets.issue("user-a");
        jdbc.update("UPDATE photo_check_ticket SET expires_at = ?",
                new Timestamp(System.currentTimeMillis() - 1000));
        assertFalse(tickets.consume(token, "user-a"));
        for (int i = 0; i < 10; i++) assertTrue(tickets.allowPrecheck("user-a"));
        assertFalse(tickets.allowPrecheck("user-a"));
        assertTrue(tickets.allowPrecheck("user-b"));
    }
}
